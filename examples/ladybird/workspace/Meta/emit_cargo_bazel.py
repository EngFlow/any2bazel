def lock_packages(rel):
    """[(name, version, checksum-or-None)] for one Cargo.lock, in lock order."""
    d = _toml(os.path.join(ROOT, rel))
    return [(p["name"], p["version"], p.get("checksum"))
            for p in d.get("package", [])]


def split_packages(pkgs):
    """(registry, workspace) — the ones with a checksum, and the ones without.

    The distinction is not cosmetic: a `[[package]]` with no `checksum` is an
    in-tree path dependency (a workspace member), i.e. a *source* Bazel already
    has. Emitting a fetch rule for it would build a URL for a crate that does
    not exist on crates.io. Emitting nothing for a registry crate is worse: the
    offline build fails with "no matching package" far from the missing rule.
    """
    registry = [(n, v, c) for (n, v, c) in pkgs if c]
    workspace = [(n, v) for (n, v, c) in pkgs if not c]
    return registry, workspace


def all_registry_crates():
    """{(name, version): sha256} across every lock file.

    Merged rather than kept per-workspace because a crate shared by both locks
    (smallvec 1.15.1, pinned `=1.15.1` by flapc) is ONE fetch: same name, same
    version, and — checked here rather than assumed — the same checksum. If the
    two locks ever disagreed on a shared crate's hash, one repo name would have
    to serve two contents, which is the silent-wrong-content bug vcpkg's
    hash-suffixed repo names exist to prevent. So it is a hard error.
    """
    out = {}
    for rel in LOCKS:
        registry, _ = split_packages(lock_packages(rel))
        for name, version, checksum in registry:
            key = (name, version)
            if key in out and out[key] != checksum:
                raise SystemExit(
                    "error: %s-%s has two different checksums across lock files "
                    "(%s vs %s)" % (name, version, out[key], checksum))
            out[key] = checksum
    return out


def crate_url(name, version):
    """The crates.io download URL. A pure function of (name, version).

    This is the whole reason no capture is needed: vcpkg's URLs are computed by a
    CMake program, crates.io's are computed by this one line.
    """
    return "https://static.crates.io/crates/%s/%s-%s.crate" % (name, name, version)


def repo_name(name, version):
    """A Bazel repo name per crate-version.

    (name, version) is already unique in a lock file, so unlike the vcpkg case
    there is no hash needed to disambiguate — but `-` and `.` are not legal in a
    repo name, so both are normalized.
    """
    return "crate_%s_%s" % (name.replace("-", "_"),
                            re.sub(r"[^A-Za-z0-9]", "_", version))


