def _arg(block, key):
    """A single-valued cmake_parse_arguments key."""
    m = re.search(key + r"\s+([^\s\)]+)", block)
    return m.group(1).strip('"') if m else None


def _multi(block, key, stops):
    """A multi-valued key: everything up to the next keyword."""
    m = re.search(key + r"\s+((?:(?!\b(?:%s)\b)[^\)])*)" % "|".join(stops), block)
    if not m:
        return []
    return [t.strip('"') for t in m.group(1).split() if t.strip('"')]


