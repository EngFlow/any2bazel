def emit_crates(crates):
    sys.stdout.write(HEADER)
    print('load("@bazel_tools//tools/build_defs/repo:http.bzl", "http_archive")')
    print()
    print("# %d crates.io crates, every sha256 lifted verbatim out of the two" % len(crates))
    print("# Cargo.lock files. Nothing is re-hashed here and nothing was captured:")
    print("# the lock file is the pin and the URL is a function of (name, version),")
    print("# so this regenerates with no cargo, no network and no CMake.")
    print("#")
    print("# A `.crate` IS a gzipped tar whose single top-level dir is")
    print("# <name>-<version>/, so http_archive unpacks it directly with")
    print("# strip_prefix and an explicit type=\"tgz\" (the .crate extension is")
    print("# not one http_archive recognises) -- no custom repository rule and no")
    print("# per-crate BUILD file: the vendor directory cargo wants is assembled")
    print("# by a normal build action later (see cargo.bzl), not at fetch time.")
    print()
    print("def cargo_crates():")
    for (name, version), sha in sorted(crates.items()):
        print("    http_archive(")
        print("        name = %r," % repo_name(name, version))
        print("        urls = [%r]," % crate_url(name, version))
        print("        sha256 = %r," % sha)
        print("        strip_prefix = %r," % ("%s-%s" % (name, version)))
        # `.crate` is not a suffix http_archive recognises, so the archive type
        # has to be stated. It IS a gzipped tar -- cargo just gives it its own
        # extension -- and without `type` the fetch fails with a confusing
        # "Expected a file with a .zip/.tar.gz/... suffix".
        print("        type = \"tgz\",")
        # A crate has no BUILD file and needs none: the staging action reads the
        # tree through a filegroup, so give every repo the same trivial one.
        print("        build_file_content = _CRATE_BUILD,")
        print("    )")
    print()
    print("# Files only -- deliberately NOT `exclude_directories = 0`. Globbing the")
    print("# directories as well makes Bazel stage both a directory and its")
    print("# contents into the sandbox, which fails with a bare \"File exists\" on")
    print("# the first one (adblock's benches/) -- a message that names the path")
    print("# but not the cause. The staging script rebuilds the tree from the file")
    print("# paths, so the directory entries were never needed.")
    print('_CRATE_BUILD = """filegroup(')
    print("    name = \"srcs\",")
    print('    srcs = glob(["**"]),')
    print('    visibility = ["//visibility:public"],')
    print(")")
    print('"""')


