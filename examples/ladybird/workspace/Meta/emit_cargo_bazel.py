#!/usr/bin/env python3
"""Emit the Bazel rules that make Bazel own fetching every Rust crate.

Ring 2, part 2 — the last one. Finding 33 closed vcpkg; this closes Rust, which
was the only reason a `git clone && bazel build //:ladybird` still needed a CMake
build first (10 production crates were consumed as a prebuilt 260 MB
`librust_combined.a` out of `Build/full/cargo/`, and `flapc` was the reference
build's binary).

The shape mirrors emit_vcpkg_bazel.py deliberately — a foreign build system owns
a recipe we do not want to reimplement, so Bazel takes fetching/hashing/
sandboxing and cargo stays the recipe. One thing is *better* here, and it is
worth naming because it is the difference between the two problems:

  **There is nothing to capture.** vcpkg needed an instrumented run
  (Meta/vcpkg_capture_assets.sh) because portfiles are CMake *programs* that
  compute their URLs at run time. `Cargo.lock` is a *manifest*: it carries a
  sha256 `checksum` for every registry crate, and crates.io's download URL is a
  pure function of (name, version). So this emitter needs no cargo, no network,
  no CMake — the lock file IS the pin, and `--check` proves it round-trips.

What it emits (one pass over the lock files, selected by flag):

  cargo_crates.bzl      one http_archive per registry crate (`.crate` is a
                        .tar.gz), sha256 straight out of Cargo.lock.
  cargo_index.bzl       the crate -> label index + CARGO_CRATE_SPECS, the
                        per-crate build recipe (features, FFI headers, manifest).
  cargo_extension.bzl   the module extension that creates those repos.
  cargo_ring.bzl        the 10 cargo_crate targets + flapc + the link group,
                        as a macro the ROOT package instantiates (the crate
                        sources live at the repo root, and glob() is
                        package-relative).
  --use-repo            the `use_repo(...)` block MODULE.bazel needs.

Three things here are load-bearing, and each was measured rather than reasoned:

  * **Features are per crate and come from CMake, not from a guess.** The spec
    for this work said `libgfx_rust` is built `--features allocator`; at the
    commit this overlay targets it is NOT (cargo fails outright: "the package
    'libgfx_rust' does not contain this feature"). The features live in
    `import_rust_crate(... FEATURES ...)` in `Libraries/*/CMakeLists.txt`, behind
    a `if (NOT BUILD_SHARED_LIBS)` for three of them, so this parses the CMake
    and reports what it found. Getting them wrong changes the ABI silently —
    the finding-23 lesson.
  * **The FFI header list is not derivable from the crate name, and CMake's own
    list is INCOMPLETE.** `libweb_rust`'s `import_rust_crate` declares one header
    (`HTML/Parser/RustFFI.h`), but its build script writes *two*: it depends on
    `libweb_html_tokenizer`, whose build script emits
    `HTMLTokenizerRustFFI.h` into the same `$FFI_OUTPUT_DIR` — and three LibWeb
    TUs include it. CMake never notices because it declares outputs it does not
    enumerate; Bazel deletes undeclared outputs. So the header list is the union
    of CMake's declaration and the observed set, and the observed set wins where
    they differ (see FFI_HEADERS_OBSERVED).
  * **The registry/workspace split is the whole reason this is cheap.** 155 of
    the 166 `[[package]]` entries have a checksum; the other 11 are the in-tree
    workspace members, which have no checksum because they are *sources*. A
    crate with no checksum must never become a fetch rule (it would 404), and a
    registry crate that silently drops out is a build failure a long way from its
    cause — so both halves are counted and reported.

Usage:
  emit_cargo_bazel.py --crates    > cargo_crates.bzl
  emit_cargo_bazel.py --index     > cargo_index.bzl
  emit_cargo_bazel.py --extension > cargo_extension.bzl
  emit_cargo_bazel.py --ring      > cargo_ring.bzl
  emit_cargo_bazel.py --use-repo            # paste into MODULE.bazel
  emit_cargo_bazel.py --report              # what resolved, and what did not
  emit_cargo_bazel.py --check <dir>         # regenerate and byte-compare
"""
